"""docs/gates.md: what the calibration chose, and what each rule is worth on dev."""

from __future__ import annotations

from typing import Any

from warehouse_qa.pipeline.gates import GateParams


def render(run_id: str, params: GateParams, evidence: dict[str, Any]) -> str:
    lines = [
        "# Gate A and Gate B: calibration on dev",
        "",
        f"Generated by `warehouse-qa eval calibrate results/{run_id}`: {evidence['combinations']:,}"
        " combinations re-decided offline from the recorded signals, so $0 of LLM calls. Dev only"
        " (60 questions); test is untouched.",
        "",
        "**Objective:** over-refusal under 5%, then utility (+1 for a right answer or a right"
        " clarify/decline, -1 for a wrong answer or answering what shouldn't be answered, 0"
        " otherwise), then strict mode accuracy, then the fewest questions stopped.",
        "",
        "## Chosen",
        "| Parameter | Value |",
        "|---|---|",
        *(f"| {k} | {v} |" for k, v in params.model_dump().items()),
        "",
        "## What each rule is worth (one change from the chosen setting)",
        "| Setting | Utility | Wrong answers | Over-refusal | Needless clarify | Modes strict /"
        " lenient | Stopped |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, o in evidence["ablation"].items():
        lines.append(
            f"| {name} | {o['utility']:.0f} | {o['wrong_answers']} | {o['over_refusal']:.1%}"
            f" | {o['needless_clarify']} | {o['strict']} / {o['lenient']} | {o['stopped']} |"
        )
    lines += [
        "",
        "## Ranking quality: AURC by retrieval signal and weight (lower is better)",
        "`w` is the retrieval signal's share of the confidence. `w=0.0` (verification alone) and"
        " `w=1.0` (retrieval alone) are for comparison: the PRD's confidence combines both.",
        "",
        "| Signal, weight | AURC |",
        "|---|---|",
        *(f"| {k} | {v} |" for k, v in evidence["aurc"].items()),
        "",
        "## Risk-coverage on dev (chosen confidence)",
        "| Confidence at least | Coverage | Risk |",
        "|---|---|---|",
        *(
            f"| {p['threshold']:.4f} | {p['coverage']:.1%} | {p['risk']:.1%} |"
            for p in evidence["curve"]
        ),
    ]
    return "\n".join(lines) + "\n"
