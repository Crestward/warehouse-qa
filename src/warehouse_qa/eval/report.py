"""results/<run_id>/report.md: the human-readable view of summary.json."""

from __future__ import annotations

from collections.abc import Sequence
from typing import Any

from warehouse_qa.eval.metrics import K_VALUES, Score
from warehouse_qa.eval.records import QuestionRecord
from warehouse_qa.eval.schema import EvalQuestion


def _fmt(rate: dict[str, Any]) -> str:
    if not rate or rate.get("rate") is None:
        return "n/a"
    low, high = rate["ci95"]
    return f"{rate['rate']:.1%} [{low:.1%}, {high:.1%}] (n={rate['n']})"


def render_report(
    summary: dict[str, Any],
    records: Sequence[QuestionRecord],
    scores: Sequence[Score],
    questions: dict[str, EvalQuestion],
) -> str:
    m = summary["metrics"]
    o = m["overall"]
    cfg = summary["config"]
    run = summary.get("run", {})
    lines = [
        f"# Eval report: {summary['run_id']}",
        "",
        f"Config `{cfg['name']}` (system `{cfg['system']}`, model `{cfg['model']}`, effort"
        f" `{cfg.get('effort')}`, batch {cfg.get('batch')}) on split `{cfg['split']}`."
        f" Generated by `warehouse-qa eval run`; re-scored offline by `eval rescore`.",
        "Rates show the mean with a 95% bootstrap CI over questions.",
        "",
        "## Headline",
        "| Metric | Value |",
        "|---|---|",
        f"| Execution accuracy | {_fmt(o['execution_accuracy'])} |",
        f"| Mode accuracy (strict) | {_fmt(o['mode_accuracy'])} |",
        f"| Mode accuracy (lenient) | {_fmt(o['mode_accuracy_lenient'])} |",
        f"| Trap avoidance | {_fmt(o['trap_avoidance'])} |",
        f"| Over-refusal (allowed questions) | {_fmt(o['over_refusal'])} |",
        f"| Leakage | {_fmt(o['leakage'])} |",
    ]
    for k in K_VALUES:
        lines.append(f"| Recall@{k} | {_fmt(m['recall'][str(k)])} |")
    c = m["cost"]
    lines += [
        f"| LLM cost, nominal (this run) | ${c['usd']:.4f}"
        f" (${c['usd_per_question'] or 0:.5f}/question) |",
        f"| LLM cost, actually billed | ${run.get('spent_usd', 0):.4f}"
        " (response-cache hits are free) |",
        f"| Tokens | {c['tokens']:,} |",
        f"| Latency p50 / p95 | {c['latency_p50_s']} s / {c['latency_p95_s']} s |",
        "",
        "## By category",
        "| Category | n | Execution acc. | Mode acc. | Trap avoidance |",
        "|---|---|---|---|---|",
    ]
    for cat, b in m["by_category"].items():
        lines.append(
            f"| {cat} | {b['n']} | {_fmt(b['execution_accuracy'])} | {_fmt(b['mode_accuracy'])}"
            f" | {_fmt(b['trap_avoidance'])} |"
        )
    lines += [
        "",
        "## By role",
        "| Role | n | Execution acc. | Mode acc. | Leakage |",
        "|---|---|---|---|---|",
    ]
    for role, b in m["by_role"].items():
        lines.append(
            f"| {role} | {b['n']} | {_fmt(b['execution_accuracy'])} | {_fmt(b['mode_accuracy'])}"
            f" | {_fmt(b['leakage'])} |"
        )
    lines += ["", "## Trap avoidance by trap type", "| Trap | Avoided |", "|---|---|"]
    for t, r in m["by_trap_type"].items():
        lines.append(f"| {t} | {_fmt(r)} |")

    by_id = {s.id: s for s in scores}
    lines += [
        "",
        "## Per question",
        "| id | category | role | expected | predicted | exec | trap | leaks | note |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in sorted(records, key=lambda r: r.id):
        s, q = by_id[r.id], questions[r.id]
        note = r.sql_check or r.error or ""
        lines.append(
            f"| {r.id} | {q.category} | {q.role} | {q.expected_mode} | {r.predicted_mode}"
            f" | {_mark(s.exec_correct)} | {_mark(s.trap_avoided)} | {len(r.leaks)}"
            f" | {note[:80].replace('|', '/')} |"
        )
    if summary.get("gold_errors"):
        lines += ["", f"**Gold queries that failed:** {', '.join(summary['gold_errors'])}"]
    return "\n".join(lines) + "\n"


def _mark(v: bool | None) -> str:
    return "" if v is None else ("✓" if v else "✗")
